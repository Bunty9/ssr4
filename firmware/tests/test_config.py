"""Static checks of the firmware sources; no build, no target, no netlist needed."""

import re
import tomllib
from pathlib import Path

FIRMWARE = Path(__file__).resolve().parents[1]
ADC_MAX_V = 2.5  # ESP32-C3 datasheet v2.4 Table 5-6 p56: ATTEN3 (12 dB) measures 0-2500 mV


def _sub(text: str, name: str) -> float:
    return float(re.search(rf'^\s+{name}: "([^"]+)"', text, re.M).group(1))


def test_fault_limits_come_from_the_divider_and_adc_range(logic_yaml, ntc_volts):
    def sub(name):
        return _sub(logic_yaml, name)

    assert sub("ntc_open_v") <= ADC_MAX_V
    assert abs(sub("ntc_short_v") - ntc_volts(110)) < 0.0005
    # cutoff and resume temperatures must be measurable, i.e. inside the trusted window
    for t in (sub("cutoff_c"), sub("resume_c")):
        assert sub("ntc_short_v") < ntc_volts(t) < sub("ntc_open_v")


def test_firmware_names_pins_only_through_the_contract():
    signals = tomllib.loads((FIRMWARE / "signals.toml").read_text(encoding="utf-8"))["signals"]
    for path in sorted(FIRMWARE.glob("**/*.yaml")):
        if ".esphome" in path.parts or path.name.startswith("secrets"):
            continue
        if path.read_text(encoding="utf-8").startswith("# Generated by"):
            continue  # the pin map generated from the netlist (pins.yaml in a published copy)
        text = re.sub(r"#.*", "", path.read_text(encoding="utf-8"))  # comments may describe, not use
        assert not re.search(r"\bGPIO\d+\b", text), (
            f"{path.name}: typed GPIO number; use a ${{<signal>_pin}} from signals.toml"
        )
        for name in re.findall(r"\$\{(\w+)_pin\}", text):
            assert name in signals, f"{path.name}: ${{{name}_pin}} is not a signal in signals.toml"
